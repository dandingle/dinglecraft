import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const root=new URL('../../',import.meta.url);
const ctx=vm.createContext({});
vm.runInContext(fs.readFileSync(new URL('src/ui/i18n_ja.js',root),'utf8')+fs.readFileSync(new URL('src/ui/i18n.js',root),'utf8')+
  ';var PNAME="Stone", WORLD={name:"New World"}, AGENTS=[{name:"Gold"}], CRW={a:{t:"My Painting"}};',ctx);
const ev=s=>vm.runInContext(s,ctx);
assert.equal(ev('I18N.locale'),'en');
assert.equal(ev('i18nText("Inventory")'),'Inventory');
ev('I18N.locale="ja"');
assert.equal(ev('i18nText("Inventory")'),'インベントリ');
assert.equal(ev('i18nText("MALGORATH, THE WORLD-EATER")'),'MALGORATH, THE WORLD-EATER');
for(const label of ['Language','English','Japanese'])assert.equal(ev(`i18nText(${JSON.stringify(label)})`),label);
assert.equal(ev('i18nText("Stone / Gold / New World / My Painting")'),'Stone / Gold / New World / My Painting');
assert.equal(ev('i18nText("/Inventory/foo StoneUsername Inventory")'),'/Inventory/foo StoneUsername インベントリ');
assert.equal(ev('i18nText("Inventory\\nStoneUsername")'),'インベントリ\nStoneUsername');
assert.equal(ev('i18nText("  Inventory  ")'),'  インベントリ  ');
ev('WORLD.name="World"');
assert.notEqual(ev('i18nText("World name")'),'World name');
assert.equal(ev('i18nText("World")'),'World');
ev('var parent={id:"",closest(){return false;}};var n={nodeValue:"Inventory",parentElement:parent};i18nNode(n)');
assert.equal(ev('n.nodeValue'),'インベントリ');
ev('I18N.locale="en";i18nNode(n)');assert.equal(ev('n.nodeValue'),'Inventory');
ev('n.nodeValue="Settings";I18N.locale="ja";i18nNode(n)');assert.notEqual(ev('n.nodeValue'),'Settings');
ev('I18N.locale="en";i18nNode(n)');assert.equal(ev('n.nodeValue'),'Settings');
ev('parent.closest=()=>true;I18N.locale="ja";n.nodeValue="Inventory";i18nNode(n)');assert.equal(ev('n.nodeValue'),'Inventory');
ev(`var attrs={title:'Inventory',placeholder:'Settings'};var el={closest(){return false;},hasAttribute(a){return a in attrs;},getAttribute(a){return attrs[a];},setAttribute(a,v){attrs[a]=v;}};i18nAttrs(el);`);
assert.equal(ev('attrs.title'),'インベントリ');
ev('I18N.locale="en";i18nAttrs(el)');assert.equal(ev('attrs.title'),'Inventory');
ev(`var CanvasRenderingContext2D=function(){this.font='bold 14px monospace';};CanvasRenderingContext2D.prototype.fillText=function(t){return {text:t,font:this.font};};CanvasRenderingContext2D.prototype.measureText=CanvasRenderingContext2D.prototype.fillText;i18nCanvas();I18N.locale='ja';var g=new CanvasRenderingContext2D();var rendered=g.fillText('Inventory');`);
assert.equal(ev('rendered.text'),'インベントリ');assert.match(ev('rendered.font'),/M PLUS 1/);assert.equal(ev('g.font'),'bold 14px monospace');
assert.equal(ev('g.measureText("Inventory").text'),'インベントリ');
assert.ok(ev('Object.keys(JA_LOCALE).length')>2000);
console.log('Japanese localization checks passed (text, names, controls, restoration, attributes, canvas).');
